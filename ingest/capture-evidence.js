/**
 * QWATT ingest — Deliverable 1 evidence capture
 * ---------------------------------------------------------------------------
 * Saves the acceptance-harness and test output of one commit as a text file, so
 * the SOW's "adapter harness output showing identical results across adapters"
 * exists as a file that anyone can regenerate and compare.
 *
 *   node ingest/capture-evidence.js [<commit>] [--out <file>]
 *
 * The commit (default HEAD) is exported with `git archive` into a temporary
 * directory and the checks run there, so uncommitted changes never reach the
 * evidence. Each check's stdout, then its stderr, then its exit status is
 * written verbatim under a header with the full commit hash, the commit date,
 * the capture time (UTC) and the Node version. Nothing in the output is edited.
 * Default --out: evidence/harness/harness-<short hash>.txt in this repository.
 * Exit 1 if any check fails. Needs only git, tar and Node.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');

/** The local checks CI runs for the engine and ingestion, then the acceptance harness on its own. */
const CHECKS = [
  ['protocol/gen.js', '--check'],
  ['protocol/conformance.test.js'],
  ['mining-rig/validators.test.js'],
  ['ingest/ingest.test.js'],
  ['ingest/harness.js'],
];

function git(args, opts = {}) {
  return execFileSync('git', args, Object.assign({ cwd: __dirname, maxBuffer: 1 << 30 }, opts));
}

function main(argv) {
  let rev = 'HEAD', out = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') out = argv[++i];
    else if (argv[i].startsWith('-')) throw new Error(`unknown option ${argv[i]}`);
    else rev = argv[i];
  }
  const root = git(['rev-parse', '--show-toplevel']).toString().trim();
  const sha = git(['rev-parse', '--verify', `${rev}^{commit}`]).toString().trim();
  const committed = git(['log', '-1', '--format=%cI', sha]).toString().trim();
  out = path.resolve(out || path.join(root, 'evidence', 'harness', `harness-${sha.slice(0, 7)}.txt`));

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `qwatt-d1-${sha.slice(0, 7)}-`));
  try {
    execFileSync('tar', ['-x', '-C', dir], { input: git(['archive', '--format=tar', sha], { cwd: root }) });
    const self = path.relative(root, __filename).split(path.sep).join('/');
    const lines = [
      'QWATT · Deliverable 1 · acceptance harness and test output',
      '',
      `command    node ${self} ${argv.join(' ')}`.trimEnd(),
      `commit     ${sha}  (committed ${committed})`,
      'source     git archive of that commit, run in a temporary directory; the working tree is not used',
      `captured   ${new Date().toISOString().replace(/\.\d{3}Z$/, 'Z')}`,
      `node       ${process.version} (${process.platform} ${process.arch})`,
      'input      generated by ingest/harness.js from a fixed seed (simulated samples); its Modbus path',
      '           polls a local Modbus TCP simulator. No physical meter is read.',
      '',
    ];
    let failed = 0;
    for (const args of CHECKS) {
      const r = spawnSync(process.execPath, args, { cwd: dir, encoding: 'utf8', timeout: 10 * 60 * 1000 });
      const status = r.error ? `error: ${r.error.message}` : (r.status === null ? `signal ${r.signal}` : r.status);
      if (status !== 0) failed++;
      lines.push(`$ node ${args.join(' ')}`);
      if (r.stdout) lines.push(r.stdout.replace(/\n+$/, ''));
      if (r.stderr) lines.push('[stderr]', r.stderr.replace(/\n+$/, ''));
      lines.push(`[exit ${status}]`, '');
    }
    lines.push(`summary    ${CHECKS.length - failed} of ${CHECKS.length} checks exited 0`, '');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, lines.join('\n'));
    console.log(`[evidence] ${path.relative(process.cwd(), out)} · commit ${sha.slice(0, 7)} · ${CHECKS.length - failed}/${CHECKS.length} checks passed`);
    return failed ? 1 : 0;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

if (require.main === module) {
  try { process.exit(main(process.argv.slice(2))); }
  catch (e) { console.error(`[evidence] ${e.message}`); process.exit(2); }
}

module.exports = { CHECKS };
